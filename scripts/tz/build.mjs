// Writes src/game/tzCoords.ts: roughly where each time zone is (the latitude and
// longitude of its main city, to the nearest degree), so the game can work out
// sunrise and sunset from the device's time zone without asking for location.
// Reads the system tz database (zone.tab for coordinates, tzdata.zi for old
// names like US/Eastern or Asia/Calcutta). Run: node scripts/tz/build.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const DIR = process.argv[2] ?? '/usr/share/zoneinfo'
const deg = (s, w) => {
  const sign = s[0] === '-' ? -1 : 1
  const d = Number(s.slice(1, 1 + w)), m = Number(s.slice(1 + w, 3 + w)), sec = Number(s.slice(3 + w) || 0)
  return Math.round(sign * (d + m / 60 + sec / 3600))
}
const coords = new Map()
for (const line of readFileSync(`${DIR}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [, c, zone] = line.split('\t')
  const m = /^([+-]\d+)([+-]\d+)$/.exec(c)
  coords.set(zone, [deg(m[1], 2), deg(m[2], 3)])
}
for (const line of readFileSync(`${DIR}/tzdata.zi`, 'utf8').split('\n')) {
  const [tag, target, alias] = line.split(' ')
  if (tag === 'L' && coords.has(target) && !coords.has(alias)) coords.set(alias, coords.get(target))
}
// Grouped by area to keep it small: { America: 'New_York 41 -74,...' }.
const areas = {}
for (const [zone, [lat, lon]] of [...coords].sort()) {
  const i = zone.indexOf('/')
  const area = i < 0 ? '' : zone.slice(0, i)
  ;(areas[area] ??= []).push(`${zone.slice(i + 1)} ${lat} ${lon}`)
}
const body = Object.entries(areas).map(([a, list]) => `  ${JSON.stringify(a)}: ${JSON.stringify(list.join(','))},`).join('\n')
writeFileSync(new URL('../../src/game/tzCoords.ts', import.meta.url), `// Generated by scripts/tz/build.mjs from the tz database. Do not edit.
// Each time zone's main city as "City lat lon", grouped by area.
export const TZ_COORDS: Record<string, string> = {
${body}
}
`)
console.log(`${coords.size} zones`)
