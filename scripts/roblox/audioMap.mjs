// Packs the sound effects into one sprite (Roblox caps audio uploads a month, so the short
// effects ride on one asset and play with Sound.PlaybackRegion) and writes Data/Audio.luau
// from json/audio.json. scripts/roblox/audio.mjs runs it; it also runs alone on a kit:
//   node scripts/roblox/audioMap.mjs [outDir]
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const SR = 44100
const GAP = 0.25 // silence between effects, so a region never clips its neighbour

const pcm = (file) => execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-i', file, '-f', 's16le', '-ac', '2', '-ar', String(SR), '-'], { maxBuffer: 1 << 30 })

export function buildSprite(out, map) {
  const names = Object.keys(map.Sfx).sort()
  const gap = Buffer.alloc(Math.round(GAP * SR) * 4)
  const parts = []
  let at = 0
  for (const name of names) {
    const raw = pcm(join(out, 'Audio', map.Sfx[name].file))
    const secs = raw.length / 4 / SR
    map.Sfx[name].sprite = { start: Number(at.toFixed(3)), stop: Number((at + secs).toFixed(3)) }
    parts.push(raw, gap)
    at += secs + GAP
  }
  const file = 'sfx-sprite.mp3'
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-f', 's16le', '-ac', '2', '-ar', String(SR), '-i', '-', '-codec:a', 'libmp3lame', '-b:a', '160k', join(out, 'Audio', file)], { input: Buffer.concat(parts), maxBuffer: 1 << 30 })
  map.SfxSprite = { file, seconds: Number(at.toFixed(1)), assetId: '' }
}

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/
function luau(v, ind = '') {
  if (v === null || v === undefined) return 'nil'
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (typeof v === 'string') return JSON.stringify(v)
  const next = ind + '\t'
  if (Array.isArray(v)) {
    if (!v.length) return '{}'
    if (v.every((x) => typeof x !== 'object')) return `{ ${v.map((x) => luau(x)).join(', ')} }`
    return `{\n${v.map((x) => next + luau(x, next)).join(',\n')},\n${ind}}`
  }
  const ks = Object.keys(v)
  if (!ks.length) return '{}'
  return `{\n${ks.map((k) => `${next}${IDENT.test(k) ? k : `[${JSON.stringify(k)}]`} = ${luau(v[k], next)}`).join(',\n')},\n${ind}}`
}

export function writeMap(out, map) {
  writeFileSync(join(out, 'json', 'audio.json'), JSON.stringify(map, null, 1))
  writeFileSync(
    join(out, 'Data', 'Audio.luau'),
    `-- Generated by scripts/roblox/audio.mjs from the game's synthesised audio in github.com/KeganBerg/Cartopia.\n` +
      `-- Upload each file under Audio/ to Roblox, then put its asset id number in assetId (HANDOFF.md, Audio).\n` +
      `-- Sound effects: upload Audio/sfx-sprite.mp3 once, set SfxSprite.assetId, and play an effect with\n` +
      `-- PlaybackRegionsEnabled = true and PlaybackRegion = NumberRange.new(Sfx[name].sprite.start, Sfx[name].sprite.stop).\n\nreturn ${luau(map)}\n`,
  )
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = resolve(process.argv[2] ?? 'roblox-export')
  const map = JSON.parse(readFileSync(join(out, 'json', 'audio.json'), 'utf8'))
  buildSprite(out, map)
  writeMap(out, map)
  console.log(`sprite: ${Object.keys(map.Sfx).length} effects, ${map.SfxSprite.seconds} s`)
}
