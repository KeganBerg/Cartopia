// node scripts/playercard/shoot.mjs <outDir>   (needs vite on :5173). The Car Meet, then a player's
// profile card opened from their name and from one of their cars, on phone and desktop.
import { createRequire } from 'node:module'
const { chromium } = createRequire('/opt/node-tools/node_modules/')('playwright')
const [, , out = 'playercard-out'] = process.argv
const b = await chromium.launch({ executablePath: process.env.CHROME ?? '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const up = (n) => ({ engine: n, turbo: n, tires: n, weight: n })
const cars = [{ uid: 't1', model: 'trail', color: '#0d47a1', upgrades: up(2) }, { uid: 'z1', model: 'miata', color: '#d32f2f', upgrades: up(1) }]
for (const [form, size] of [['phone', { width: 390, height: 844 }], ['desktop', { width: 1280, height: 800 }]].filter(([f]) => !process.env.ONLY || f === process.env.ONLY)) {
  const p = await b.newPage({ viewport: size, deviceScaleFactor: form === 'phone' ? 2 : 1, isMobile: form === 'phone', hasTouch: form === 'phone' })
  p.on('pageerror', (e) => console.log('error', e.message))
  await p.addInitScript(() => localStorage.setItem('cartopia-flash-warning-hide', '1'))
  await p.goto('http://localhost:5173/?time=0.3&season=fall')
  await p.waitForFunction(() => window.__game, null, { timeout: 90000 })
  await p.locator('#splash button.ld').click({ timeout: 60000 }).catch(() => {})
  await p.waitForSelector('#splash', { state: 'detached', timeout: 20000 }).catch(() => {})
  await p.addStyleTag({ content: '*{animation-duration:0s!important;transition:none!important}' })
  await p.evaluate((cars) => {
    const g = window.__game
    g.setState({ tutorial: 99, level: 20, cars, raceCar: 't1', selectedCar: 't1', panel: null })
    g.getState().openPanel('meet')
  }, cars)
  await p.waitForSelector('.meet-row', { timeout: 60000 })
  await p.waitForTimeout(3000)
  const tap = (l) => (form === 'phone' ? l.tap() : l.click())
  await p.screenshot({ path: `${out}/${form}-1-meet.png`, timeout: 90000 })
  await tap(p.locator('.meet-row .meet-who').last())
  await p.waitForSelector('.pc-card .pc-stats', { timeout: 30000 })
  await p.waitForTimeout(5000)
  await p.screenshot({ path: `${out}/${form}-2-profile.png`, timeout: 90000 })
  await tap(p.locator('.pc-chip').nth(4))
  await p.waitForTimeout(4000)
  await p.screenshot({ path: `${out}/${form}-3-other-car.png`, timeout: 90000 })
  await tap(p.locator('.pc-card .close'))
  await tap(p.locator('.meet-row .meet-car').nth(1))
  await p.waitForSelector('.pc-card .pc-stats', { timeout: 30000 })
  await p.waitForTimeout(4000)
  await p.screenshot({ path: `${out}/${form}-4-from-car.png`, timeout: 90000 })
  await tap(p.locator('.pc-view .cp-btn[aria-label="Full screen"]'))
  await p.waitForTimeout(4000)
  await p.screenshot({ path: `${out}/${form}-5-inspect.png`, timeout: 90000 })
  await p.keyboard.press('Escape')
  await p.waitForTimeout(500)
  await tap(p.locator('.pc-visit'))
  await p.waitForTimeout(6000)
  await p.screenshot({ path: `${out}/${form}-6-visit.png`, timeout: 90000 })
  console.log(form, await p.evaluate(() => [window.__game.getState().panel, !!window.__game.getState().visiting]))
  await p.close()
}
await b.close()
