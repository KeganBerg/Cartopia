// Chat @mentions: the friend picker while typing "@Ga", a mention of you, and a tapped name's profile.
// node scripts/mentionshot/shoot.mjs <outDir>   (needs `npm run dev` on :5173)
import { chromium } from 'playwright'
const [, , out = 'mention-out'] = process.argv
const b = await chromium.launch({ executablePath: process.env.CHROME ?? '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
for (const [form, size] of [['desktop', { width: 1280, height: 800 }], ['phone', { width: 390, height: 844 }]]) {
  const p = await b.newPage({ viewport: size, deviceScaleFactor: form === 'phone' ? 2 : 1, hasTouch: form === 'phone' })
  p.on('pageerror', (e) => console.log('error', e.message))
  await p.addInitScript(() => localStorage.setItem('cartopia-flash-warning-hide', '1'))
  await p.goto('http://localhost:5173/?time=0.3&season=fall&chatdemo')
  await p.waitForFunction(() => window.__game, null, { timeout: 90000 })
  await p.locator('#splash button.ld').click({ timeout: 60000 }).catch(() => {})
  await p.waitForSelector('#splash', { state: 'detached', timeout: 20000 }).catch(() => {})
  await p.waitForTimeout(2500)
  await p.evaluate(() => { window.__game.setState({ tutorial: 99 }); window.__game.getState().openPanel('chat') })
  await p.waitForTimeout(1200)
  await p.locator('.chat-rooms button').first().click()
  await p.waitForTimeout(500)
  const box = p.locator('.chat-send input')
  await box.click()
  await box.pressSequentially('Thanks @Ga', { timeout: 120000 })
  await p.waitForTimeout(600)
  await p.screenshot({ path: `${out}/${form}-1-picker.png` })
  await p.keyboard.press('Enter')
  await p.waitForTimeout(300)
  console.log(form, 'after pick:', await box.inputValue())
  await p.screenshot({ path: `${out}/${form}-2-picked.png` })
  await p.locator('.chat-bubble .mention', { hasText: '@Gabe' }).first().click()
  await p.waitForTimeout(2500)
  await p.screenshot({ path: `${out}/${form}-3-profile.png` })
  // Closed chat: the Chat button shows "@" while a mention waits.
  await p.keyboard.press('Escape')
  await p.evaluate(() => window.__game.setState({ panel: null, level: 20 }))
  await p.evaluate(() => import('/src/lib/chat.ts').then(({ useChat }) => { useChat.setState({ pinged: { global: 1, crew: 0 } }) }))
  await p.waitForTimeout(800)
  await p.screenshot({ path: `${out}/${form}-4-badge.png` })
  await p.close()
}
await b.close()
