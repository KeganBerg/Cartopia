// Admin skips level locks: the Showroom at level 1 as admin, and the give-car picker asking for a reason.
// node scripts/adminshot/locks.mjs <outDir>   (needs `npm run dev` on :5173)
import { chromium } from 'playwright'
const [, , out = 'admin-out'] = process.argv
const b = await chromium.launch({ executablePath: process.env.CHROME ?? '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const forms = [['desktop', { width: 1280, height: 800 }], ['phone', { width: 390, height: 844 }]].filter(([f]) => !process.env.FORM || process.env.FORM === f)
for (const [form, size] of forms) {
  const p = await b.newPage({ viewport: size, deviceScaleFactor: form === 'phone' ? 2 : 1 })
  p.on('pageerror', (e) => console.log('error', e.message))
  await p.addInitScript(() => localStorage.setItem('cartopia-flash-warning-hide', '1'))
  await p.goto('http://localhost:5173/?time=0.3&season=fall')
  await p.waitForFunction(() => window.__game, null, { timeout: 90000 })
  await p.locator('#splash button.ld').click({ timeout: 60000 }).catch(() => {})
  await p.waitForSelector('#splash', { state: 'detached', timeout: 20000 }).catch(() => {})
  await p.waitForTimeout(2500)
  await p.evaluate(async () => {
    const { admin } = await import('/src/lib/admin.ts')
    const bob = { id: 'b', username: 'TurboBob', town: 'Bobville', level: 1, coins: 1200, gems: 5, parts: 3, muted: null, admin: false, joined: '', seen: '',
      cars: [{ uid: 'c1', model: 'pip', color: '#e53935' }], chat: [] }
    const ok = (data) => Promise.resolve({ data, error: null })
    admin.find = () => ok([bob])
    admin.player = () => ok(bob)
    window.__game.setState({ tutorial: 99 })
  })
  await p.waitForTimeout(2500)
  await p.evaluate(() => window.__game.setState({ panel: null, panelBack: [], level: 1, admin: true, coins: 1e12, bucks: 1e12 }))
  await p.evaluate(() => window.__game.getState().openPanel('showroom'))
  await p.waitForTimeout(2500)
  await p.screenshot({ path: `${out}/${form}-1-showroom-admin.png` })
  await p.evaluate(() => window.__game.setState({ admin: false }))
  await p.waitForTimeout(1500)
  await p.screenshot({ path: `${out}/${form}-2-showroom-player.png` })
  await p.evaluate(() => window.__game.setState({ admin: true }))
  await p.evaluate(() => window.__game.getState().openPanel('admin'))
  await p.waitForTimeout(1200)
  await p.locator('.sheet-tabs button', { hasText: 'Players' }).click()
  await p.locator('.adm-input').fill('bob')
  await p.waitForTimeout(900)
  await p.locator('.adm-row').first().click()
  await p.waitForTimeout(2000)
  await p.locator('input[aria-label="Find a car"]').fill('ae')
  await p.waitForTimeout(2500)
  await p.locator('.adm-car.pick').first().click()
  await p.waitForTimeout(400)
  await p.screenshot({ path: `${out}/${form}-3-needs-reason.png` })
  await p.locator('.adm-input').first().fill('gift')
  await p.locator('.adm-car.pick').first().click()
  await p.waitForTimeout(500)
  await p.screenshot({ path: `${out}/${form}-4-give-confirm.png` })
  await p.locator('.cf-no').click()
  await p.locator('.panel-body').evaluate((el) => (el.scrollTop = 0))
  await p.locator('.adm-max').nth(3).click()
  await p.waitForTimeout(300)
  await p.screenshot({ path: `${out}/${form}-5-xp.png` })
  console.log(form)
  await p.close()
}
await b.close()
