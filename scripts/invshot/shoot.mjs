import { chromium } from 'playwright'
const out = process.argv[2]
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
for (const [form, size] of [['desktop', { width: 1280, height: 800 }], ['phone', { width: 390, height: 844 }]]) {
  const p = await b.newPage({ viewport: size, deviceScaleFactor: form === 'phone' ? 2 : 1, isMobile: form === 'phone', hasTouch: form === 'phone' })
  p.on('pageerror', (e) => console.log('pageerror', e.message))
  await p.addInitScript(() => localStorage.setItem('cartopia-flash-warning-hide', '1'))
  await p.goto('http://localhost:5173/?time=0.3&season=fall&from=tiktok&join=MR&ref=speedy')
  await p.waitForFunction(() => window.__game, null, { timeout: 180000 })
  await p.waitForTimeout(3000)
  console.log(form, 'url after load', await p.evaluate(() => location.search), await p.evaluate(() => localStorage.getItem('cartopia.arrival')), await p.evaluate(() => localStorage.getItem('cartopia.crewInvite')))
  await p.evaluate(() => window.__game.setState({ tutorial: 99, level: 25, panel: null }))
  await p.waitForTimeout(1500)
  await p.evaluate(() => window.__game.getState().openPanel('friends'))
  await p.waitForSelector('.fr-invite', { timeout: 60000 })
  await p.waitForTimeout(1500)
  await p.screenshot({ path: `${out}/${form}-1-friends-invite.png` })
  await p.evaluate(() => window.__game.getState().openPanel('account'))
  await p.waitForTimeout(1500)
  await p.getByText('❓ Help').first().click()
  await p.waitForTimeout(800)
  await p.evaluate(() => [...document.querySelectorAll('.set-link')].find((e) => e.textContent.includes('Invite'))?.scrollIntoView({ block: 'center' }))
  await p.waitForTimeout(600)
  await p.screenshot({ path: `${out}/${form}-2-help-invite.png` })
  const wide = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  console.log(form, 'page overflows', wide)
  await p.close()
}
await b.close()
